BEGIN;

CREATE TABLE IF NOT EXISTS cargas (
    id_carga integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_operacion integer NOT NULL REFERENCES operaciones(id_operacion),
    descripcion text NOT NULL,
    tipo_mercancia text,
    peso_kg numeric(12,2) CHECK (peso_kg >= 0),
    volumen_m3 numeric(12,3) CHECK (volumen_m3 >= 0),
    cantidad_paquetes integer CHECK (cantidad_paquetes > 0),
    remitente text,
    destinatario text,
    requiere_refrigeracion boolean NOT NULL DEFAULT false,
    fecha_registro timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS alertas (
    id_alerta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_operacion integer REFERENCES operaciones(id_operacion),
    tipo text NOT NULL,
    severidad text NOT NULL DEFAULT 'MEDIA'
        CHECK (severidad IN ('BAJA','MEDIA','ALTA','CRITICA')),
    mensaje text NOT NULL,
    estado text NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA','ATENDIDA')),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_atencion timestamptz,
    atendida_por integer REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS entregas (
    id_entrega integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_operacion integer NOT NULL UNIQUE REFERENCES operaciones(id_operacion),
    recibido_por text NOT NULL,
    observaciones text,
    fecha_entrega timestamptz NOT NULL DEFAULT now(),
    confirmado_por integer REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS notificaciones (
    id_notificacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL REFERENCES usuarios(id_usuario),
    id_operacion integer REFERENCES operaciones(id_operacion),
    titulo text NOT NULL,
    mensaje text NOT NULL,
    leida boolean NOT NULL DEFAULT false,
    fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS integraciones (
    id_integracion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL UNIQUE,
    proveedor text,
    tipo text NOT NULL,
    habilitada boolean NOT NULL DEFAULT false,
    configuracion jsonb NOT NULL DEFAULT '{}',
    fecha_actualizacion timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE documentacion
    ADD COLUMN IF NOT EXISTS estado_validacion text DEFAULT 'PENDIENTE';

ALTER TABLE documentacion
    ADD COLUMN IF NOT EXISTS fecha_vencimiento date;

CREATE INDEX IF NOT EXISTS idx_cargas_operacion
    ON cargas(id_operacion);

CREATE INDEX IF NOT EXISTS idx_alertas_operacion
    ON alertas(id_operacion);

CREATE INDEX IF NOT EXISTS idx_alertas_estado
    ON alertas(estado);

CREATE INDEX IF NOT EXISTS idx_notificaciones_usuario
    ON notificaciones(id_usuario, leida);

CREATE INDEX IF NOT EXISTS idx_trazabilidad_operacion
    ON trazabilidad(id_operacion, fecha);

COMMIT;