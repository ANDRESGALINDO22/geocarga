BEGIN;
CREATE TABLE IF NOT EXISTS roles (
  id_rol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_rol text NOT NULL UNIQUE,
  matriz_permisos jsonb NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_rol integer NOT NULL REFERENCES roles,
  nombre_usuario text NOT NULL,
  correo text NOT NULL UNIQUE,
  contrasena text NOT NULL
);
CREATE TABLE IF NOT EXISTS vuelos (
  id_vuelo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_vuelo text NOT NULL,
  aerolinea text NOT NULL,
  origen text NOT NULL,
  destino text NOT NULL
);
ALTER TABLE vuelos ADD COLUMN IF NOT EXISTS radar_id text;
CREATE TABLE IF NOT EXISTS operaciones (
  id_operacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_vuelo integer NOT NULL REFERENCES vuelos,
  etapa_flujo text NOT NULL,
  estado_general text NOT NULL,
  fecha_embarque timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS trazabilidad (
  id_trazabilidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer REFERENCES usuarios,
  id_operacion integer REFERENCES operaciones,
  accion text NOT NULL,
  descripcion text NOT NULL,
  fecha timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS documentacion (
  id_documento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_operacion integer NOT NULL REFERENCES operaciones,
  tipo_documento text NOT NULL,
  url_almacenamiento text NOT NULL,
  fecha_carga timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE documentacion ADD COLUMN IF NOT EXISTS contenido bytea;
CREATE TABLE IF NOT EXISTS novedades (
  id_novedad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_operacion integer NOT NULL REFERENCES operaciones,
  tipo text NOT NULL,
  descripcion text NOT NULL,
  fecha timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE novedades ADD COLUMN IF NOT EXISTS validada_en timestamptz;
ALTER TABLE novedades ADD COLUMN IF NOT EXISTS validada_por integer REFERENCES usuarios;
CREATE TABLE IF NOT EXISTS operacion_usuarios (
  id_operacion integer NOT NULL REFERENCES operaciones ON DELETE CASCADE,
  id_usuario integer NOT NULL REFERENCES usuarios ON DELETE CASCADE,
  PRIMARY KEY (id_operacion, id_usuario)
);
COMMIT;
